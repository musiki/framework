#!/usr/bin/env node
// Vendors @zztt/lilypond-client (zero-dependency ESM) into
// src/lib/vendor/lilypond-client/. The engine is built on a CI runner without
// /opt/packages, so the copy is committed. Re-run after updating the package,
// then commit the result.
//
// Source: $PLUGINS_DIR/lilypond-service/client/{index.mjs,index.d.ts,package.json}.
// Without PLUGINS_DIR the first of /opt/packages, ../packages, ../../packages
// (relative to the repo root) that contains lilypond-service/client/ is used;
// locally the engine lives at ~/projects/26-musiki/framework and the package at
// ~/projects/packages/lilypond-service.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rel = path.join('lilypond-service', 'client');
const candidates = ['/opt/packages', path.resolve(repoRoot, '..', 'packages'), path.resolve(repoRoot, '..', '..', 'packages')];
const pluginsDir = process.env.PLUGINS_DIR
  || candidates.find((dir) => fs.existsSync(path.join(dir, rel, 'index.mjs')))
  || candidates[0];
const sourceDir = path.join(pluginsDir, rel);
const targetDir = path.join(repoRoot, 'src', 'lib', 'vendor', 'lilypond-client');

for (const file of ['index.mjs', 'index.d.ts', 'package.json']) {
  if (!fs.existsSync(path.join(sourceDir, file))) {
    console.error(`lilypond-client source not found: ${path.join(sourceDir, file)} (set PLUGINS_DIR)`);
    process.exit(1);
  }
}

const pkg = JSON.parse(fs.readFileSync(path.join(sourceDir, 'package.json'), 'utf8'));
const version = String(pkg.version || '');
if (pkg.name !== '@zztt/lilypond-client' || !/^\d+\.\d+\.\d+$/.test(version)) {
  console.error(`unexpected package at ${sourceDir}: ${pkg.name}@${version}`);
  process.exit(1);
}

const header = (file) => [
  `// @zztt/lilypond-client@${version} — vendored copy of ${file}.`,
  '// Generated by scripts/vendor-lilypond-client.mjs; do not edit here, edit the',
  '// package (lilypond-service/client) and re-run the script.',
  '',
].join('\n');

const js = fs.readFileSync(path.join(sourceDir, 'index.mjs'), 'utf8');
const dts = fs.readFileSync(path.join(sourceDir, 'index.d.ts'), 'utf8');

fs.mkdirSync(targetDir, { recursive: true });
fs.writeFileSync(
  path.join(targetDir, 'index.mjs'),
  `${header('index.mjs')}${js.trimEnd()}\n\nexport const LILYPOND_CLIENT_VERSION = '${version}';\n`,
);
fs.writeFileSync(
  path.join(targetDir, 'index.d.ts'),
  `${header('index.d.ts')}${dts.trimEnd()}\n\nexport declare const LILYPOND_CLIENT_VERSION: string;\n`,
);
console.log(`vendored @zztt/lilypond-client ${version} from ${sourceDir} -> ${path.relative(repoRoot, targetDir)}`);
