BEGIN;

-- Cohortes.
--
-- Hasta acá "Enrollment" no tenía ninguna dimensión de período: una materia era
-- una lista plana de inscriptos, para siempre. Al empezar 2027 los alumnos de 2026
-- seguían adentro, no había forma de abrir una comisión 2, y las entregas se
-- acumulaban sin frontera de cuatrimestre.
--
-- La migración es aditiva a propósito: 26 archivos consultan "Enrollment" y
-- ninguno sabe de cohortes todavía. "cohortId" es nullable y no hay unique sobre
-- (userId, courseId) que haya que tocar, así que todas las consultas existentes
-- siguen devolviendo lo mismo. El filtrado por cohorte se agrega después, donde
-- corresponda, y no de golpe.

CREATE TABLE IF NOT EXISTS public."Cohort" (
  "id"        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "courseId"  text        NOT NULL,
  -- Texto libre y visible: "2027", "2027 · Comisión 2", "2027 · 2do cuatrimestre".
  "label"     text        NOT NULL,
  "year"      integer,
  -- "anual", "1c", "2c", o lo que la materia necesite.
  "term"      text,
  "startsAt"  date,
  "endsAt"    date,
  "isActive"  boolean     NOT NULL DEFAULT false,
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "createdBy" uuid        REFERENCES public."User" ("id") ON DELETE SET NULL
);

-- Dos cohortes de la misma materia no pueden llamarse igual.
CREATE UNIQUE INDEX IF NOT EXISTS "Cohort_courseId_label_key"
  ON public."Cohort" ("courseId", "label");

-- Una sola cohorte activa por materia. Es índice parcial: las inactivas no compiten.
CREATE UNIQUE INDEX IF NOT EXISTS "Cohort_one_active_per_course"
  ON public."Cohort" ("courseId") WHERE "isActive";

CREATE INDEX IF NOT EXISTS "Cohort_courseId_idx" ON public."Cohort" ("courseId");

ALTER TABLE public."Enrollment"
  ADD COLUMN IF NOT EXISTS "cohortId" bigint
  REFERENCES public."Cohort" ("id") ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS "Enrollment_cohortId_idx" ON public."Enrollment" ("cohortId");
CREATE INDEX IF NOT EXISTS "Enrollment_courseId_idx" ON public."Enrollment" ("courseId");

-- Backfill: una cohorte "Histórica" por materia, activa, con todo lo que ya existe.
-- Queda activa para que nada cambie hoy; al crear la cohorte 2027 se desactiva sola.
INSERT INTO public."Cohort" ("courseId", "label", "isActive")
SELECT DISTINCT e."courseId", 'Histórica', true
FROM public."Enrollment" e
WHERE e."courseId" IS NOT NULL AND e."courseId" <> ''
ON CONFLICT ("courseId", "label") DO NOTHING;

UPDATE public."Enrollment" e
SET "cohortId" = c."id"
FROM public."Cohort" c
WHERE e."cohortId" IS NULL
  AND c."courseId" = e."courseId"
  AND c."label" = 'Histórica';

COMMIT;
